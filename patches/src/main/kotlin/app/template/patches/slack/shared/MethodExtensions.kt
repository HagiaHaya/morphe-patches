package app.template.patches.slack.shared

import app.morphe.patcher.extensions.InstructionExtensions.addInstructions
import app.morphe.patcher.patch.BytecodePatchContext
import app.morphe.patcher.util.proxy.mutableTypes.MutableClass
import app.morphe.patcher.util.proxy.mutableTypes.MutableMethod
import app.morphe.patcher.util.proxy.mutableTypes.MutableMethod.Companion.toMutable
import com.android.tools.smali.dexlib2.builder.MutableMethodImplementation
import com.android.tools.smali.dexlib2.immutable.ImmutableMethod
import com.android.tools.smali.dexlib2.immutable.ImmutableMethodParameter

internal const val SINGLE_CLASS = "Lio/reactivex/rxjava3/core/Single;"

/**
 * Renames [method] and adds a method with its former name and signature, so the new method can
 * call the original one. The methods of a class are kept in a set, so the method is removed
 * while its name, which is part of its hash, changes.
 */
internal fun MutableClass.wrapMethod(method: MutableMethod, originalName: String, registerCount: Int, smali: String) {
    val name = method.name
    methods.remove(method)
    method.name = originalName
    methods.add(method)

    methods.add(
        ImmutableMethod(
            method.definingClass,
            name,
            method.parameters.map { ImmutableMethodParameter(it.type, null, null) },
            method.returnType,
            method.accessFlags,
            null,
            null,
            MutableMethodImplementation(registerCount),
        ).toMutable().apply { addInstructions(0, smali) }
    )
}


/**
 * Replaces the code of [method] with [smali], which uses [registerCount] registers including
 * the parameters. Used for methods of the extension whose code is generated by the patch, as
 * the compiler gives a placeholder body fewer registers than the generated code needs.
 */
internal fun MutableClass.replaceMethod(method: MutableMethod, registerCount: Int, smali: String) {
    methods.remove(method)
    methods.add(
        ImmutableMethod(
            method.definingClass,
            method.name,
            method.parameters.map { ImmutableMethodParameter(it.type, null, null) },
            method.returnType,
            method.accessFlags,
            null,
            null,
            MutableMethodImplementation(registerCount),
        ).toMutable().apply { addInstructions(0, smali) }
    )
}

/**
 * @return The reference to a method of the Single class of RxJava. R8 changed their return types
 * to the classes of the operators, which differ between app versions.
 */
internal fun BytecodePatchContext.singleMethod(name: String, parameterType: String) =
    classDefBy(SINGLE_CLASS).methods.singleOrNull {
        it.name == name && it.parameterTypes.map(CharSequence::toString) == listOf(parameterType)
    }?.let { "$SINGLE_CLASS->$name($parameterType)${it.returnType}" }
        ?: throw IllegalStateException("Could not find $SINGLE_CLASS->$name($parameterType)")
